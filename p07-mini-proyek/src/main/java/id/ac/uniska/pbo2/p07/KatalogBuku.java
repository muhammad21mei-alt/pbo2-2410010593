    private void saring() {
        String kata = cariField.getText().trim();
        if (kata.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            // Mencari pada kolom 0 (Kode), 1 (Judul), dan 2 (Penulis)
            sorter.setRowFilter(
                    RowFilter.regexFilter("(?i)" + Pattern.quote(kata), 0, 1, 2)
            );
        }
        perbaruiStatus();
    }
    
    
    private int barisTerpilih() {
        int barisTampilan = bukuTable.getSelectedRow();
        if (barisTampilan < 0) {
            return -1;
        }
        return bukuTable.convertRowIndexToModel(barisTampilan);
    }
    
    
    private void tambah() {
        Buku baru = new DialogBuku(this, "Tambah Buku", null).tampilkan();
        if (baru != null) {
            model.tambah(baru);
            perbaruiStatus();
        }
    }
    
    
    private void ubah() {
        int baris = barisTerpilih();
        if (baris < 0) {
            return;
        }    
        Buku hasil = new DialogBuku(this, "Ubah Buku", model.get(baris)).tampilkan();
        if (hasil != null) {
            model.ubah(baris, hasil);
             perbaruiStatus();
        }
    }
    
    
    private void hapus() {
        int baris = barisTerpilih();
        if (baris < 0) {
        return;
    }
        String judul = model.get(baris).getJudul();
        int jawab = JOptionPane.showConfirmDialog(this,"Hapus buku " + judul + "?",
            "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE );
        if (jawab == JOptionPane.YES_OPTION) {
            model.hapus(baris);
            perbaruiStatus();
        }
    }
  
    
    private void perbaruiTombol() {
        boolean adaPilihan = bukuTable.getSelectedRow() >= 0;
        ubahButton.setEnabled(adaPilihan);
        hapusButton.setEnabled(adaPilihan);
        ubahItem.setEnabled(adaPilihan);
        hapusItem.setEnabled(adaPilihan);
    }
    
    
    private void perbaruiStatus() {
        int tersedia = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            if (model.get(i).getStatus() == StatusKoleksi.TERSEDIA) {tersedia++;}}
        statusLabel.setText(
                "Menampilkan "+ bukuTable.getRowCount()
                        + " dari " + model.getRowCount()
                        + " buku (" + tersedia + " tersedia)");
    }

